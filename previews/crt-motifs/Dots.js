// la palabra en mayúsculas y sin tildes; lo que no está en la fuente sale `?`
function clean(word) {
    const w = String(word || "").toUpperCase();
    const from = "ÁÀÄÂÉÈËÊÍÌÏÎÓÒÖÔÚÙÜÛÑÇ", to = "AAAAEEEEIIIIOOOOUUUUNC";
    let out = "";
    for (let i = 0; i < w.length; i++) {
        const j = from.indexOf(w.charAt(i));
        const c = j >= 0 ? to.charAt(j) : w.charAt(i);
        if (c === " " || G[c] !== undefined) out += c;
        else if (c.trim() !== "" && /[.,;:'"()-]/.test(c) === false) out += "?";
    }
    return out.trim();
}

// los puntos encendidos de `word`: [{x, y}] en celdas (columna, fila) y el
// ancho total en columnas. Letra = 5 columnas + 1 de aire.
function cells(word, maxLen) {
    const w = clean(word).slice(0, maxLen || 9);
    const pts = [];
    for (let i = 0; i < w.length; i++) {
        const g = G[w.charAt(i)];
        if (!g) continue;
        for (let k = 0; k < 35; k++)
            if (g.charAt(k) === "#")
                pts.push({ x: i * 6 + (k % 5), y: Math.floor(k / 5) });
    }
    return { pts: pts, cols: Math.max(1, w.length * 6 - 1), text: w };
}
